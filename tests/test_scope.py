"""What smells compare: which files count, which version of each is the base, and what a change made longer."""

from __future__ import annotations

import json
import shutil
import unittest

from support import BroomCase, py_function

from broom.common import ChangedLines
from broom.measure import code_lines
from broom.smells import base_texts, find_smells


class ScopeTest(BroomCase):
    def test_dependencies_build_output_and_generated_code_are_skipped(self) -> None:
        long_one = py_function("long_one", 120)
        r = self.repo({"node_modules/m/a.py": long_one, "dist/b.py": long_one,
                       "gen.py": "# Code generated by tool. DO NOT EDIT.\n" + long_one, "kept.py": long_one})
        found, _ = find_smells(r, [r / n for n in ("node_modules/m/a.py", "dist/b.py", "gen.py", "kept.py")], None)
        self.assertEqual([s.file.name for s in found if s.metric == "function_lines"], ["kept.py"])

    def test_output_like_dirs_count_where_git_tracks_them(self) -> None:
        long_one = py_function("long_one", 120)
        r = self.repo({"src/release/a.py": long_one, "vendor/v.py": long_one})
        (r / "build").mkdir()
        (r / "build/b.py").write_text(long_one)  # untracked and not ignored: build output
        found, notes = find_smells(r, [r / "src/release/a.py", r / "vendor/v.py", r / "build/b.py"], None)
        self.assertEqual([str(s.file.relative_to(r)) for s in found if s.metric == "function_lines"],
                         ["src/release/a.py"])
        self.assertIn("so not measured: vendor/", " ".join(notes), "a tracked directory skipped by name is reported")

    @unittest.skipUnless(shutil.which("jscpd"), "jscpd missing")
    def test_code_a_tracked_output_like_dir_uses_is_not_dead(self) -> None:
        r = self.repo({"pkg/__init__.py": "", "release/main.py": "print(1)\n"})
        (r / "pkg/util.py").write_text("def helper():\n    return 1\n")
        (r / "release/main.py").write_text("from pkg.util import helper\n\nprint(helper())\n")
        found, _ = find_smells(r, [r / "pkg/util.py", r / "release/main.py"], "HEAD")
        self.assertEqual([s.text() for s in found if s.metric == "dead_code" and s.file.name == "util.py"], [],
                         "a new module only a tracked release/ imports is used")

    @unittest.skipUnless(shutil.which("jscpd"), "jscpd missing")
    def test_copies_of_legacy_code_dont_count(self) -> None:
        body = py_function("one", 40).split("\n", 1)[1]
        r = self.repo({"old/a.py": "def one(x):\n" + body, ".broom.json": '{"legacy": ["old/**"]}'})
        (r / "b.py").write_text("def two(x):\n" + body)
        found, _ = find_smells(r, [r / "b.py"], "HEAD")
        self.assertEqual([s.text() for s in found if s.metric == "duplicate_lines"], [], "b.py replaces old/a.py")

    def test_test_files_get_their_own_limits(self) -> None:
        lines = "".join(f"x{i} = {i}\n" for i in range(25))
        both = {"a.py": lines, "tests/test_a.py": lines}
        cases = [('{"limits": {"file_lines": [10, 20]}, "test_limits": {"file_lines": [30, 40]}}', ["a.py"]),
                 ('{"test_limits": {"file_lines": [10, 20]}}', ["tests/test_a.py"])]
        for config, flagged in cases:
            with self.subTest(config):
                r = self.repo({**both, ".broom.json": config})
                found, _ = find_smells(r, [r / "a.py", r / "tests/test_a.py"], None)
                self.assertEqual([str(s.file.relative_to(r)) for s in found if s.metric == "file_lines"], flagged)
        item = next(i for i in self.doctor(r, self.fake_path())["items"] if i["tool"] == ".broom.json")
        self.assertIn("test limits for file_lines", item["detail"])
        (r / ".broom.json").write_text('{"legacy": "old", "test_limits": {"file_lines": [9, 3]}}')
        item = next(i for i in self.doctor(r, self.fake_path())["items"] if i["tool"] == ".broom.json")
        self.assertIn("legacy must be a list of globs", item["detail"])
        self.assertIn("test_limits: file_lines must be [soft, hard]", item["detail"])

    def test_smells_leave_out_what_the_repo_excludes(self) -> None:
        r = self.repo({"gen/a.py": py_function("huge", 120), ".broom.json": '{"exclude": ["gen/**"]}'})
        self.assertEqual(json.loads(self.cli(r, "smells", "--json").stdout)["total"], 0)

    def test_smells_base_lists_what_the_changes_made_worse(self) -> None:
        r = self.repo({"a.py": py_function("legacy", 120), "b.py": "x = 1\n", "c.py": py_function("old", 110)})
        (r / "a.py").write_text(py_function("legacy", 125))
        (r / "b.py").write_text(py_function("fresh", 130).replace("+=", "-="))
        data = json.loads(self.cli(r, "smells", "--base", "HEAD", "--json").stdout)
        self.assertEqual(data["base"], "HEAD")
        sized = sorted((s["file"], s["was"]) for s in data["smells"] if s["smell"] == "function_lines")
        self.assertEqual(sized, [("a.py", 120), ("b.py", None)], "c.py is as it was")
        self.assertIn("the changes since HEAD made worse", self.cli(r, "smells", "--base", "HEAD").stdout)
        self.assertIsNone(json.loads(self.cli(r, "smells", "--json").stdout)["base"])
        self.assertIn("unknown revision", self.cli(r, "smells", "--base", "nope").stderr)

    def test_base_texts_reads_many_files_in_one_go(self) -> None:
        r = self.repo({"a.py": "a = 1\n", "b.py": "b = 2\n"})
        wanted = ["a.py", "gone.py", "new dir/with space.py", "b.py"]
        self.assertEqual(base_texts(r, "HEAD", wanted), {"a.py": "a = 1\n", "b.py": "b = 2\n"})

    def test_a_moved_file_is_measured_against_its_old_path(self) -> None:
        r = self.repo({"a.py": py_function("huge", 120)})
        self.sh(r, "git", "mv", "a.py", "b.py")
        found, _ = find_smells(r, [r / "b.py"], "HEAD")
        self.assertEqual([s.text() for s in found], [], "a move makes nothing new: not the length, not dead code")
        (r / "b.py").write_text(py_function("huge", 125))
        found, _ = find_smells(r, [r / "b.py"], "HEAD")
        self.assertIn("huge is 125 lines long (hard limit 100; was 120)", [s.text() for s in found])

    def test_a_moved_file_changes_only_the_lines_edited_after_the_move(self) -> None:
        text = "".join(f"x{i} = {i}\n" for i in range(20))
        r = self.repo({"a.py": text})
        self.sh(r, "git", "mv", "a.py", "b.py")
        self.assertEqual(ChangedLines().get(r / "b.py"), set(), "so its old lint findings stay old")
        (r / "b.py").write_text(text.replace("x5 = 5\n", "x5 = 55\n"))
        self.assertEqual(ChangedLines().get(r / "b.py"), {6})
        self.assertEqual(ChangedLines(cached=True).get(r / "b.py"), set(), "the index holds the plain move")

    def test_imports_alone_dont_make_a_long_file_worse(self) -> None:
        code = "".join(f"x{i} = {i}\n" for i in range(25))
        r = self.repo({"a.py": code, ".broom.json": '{"limits": {"file_lines": [10, 20]}}'})
        (r / "a.py").write_text("import os\nfrom pathlib import (\n    Path,\n)\n" + code)
        found, _ = find_smells(r, [r / "a.py"], "HEAD")
        self.assertEqual([s.text() for s in found if s.metric == "file_lines"], [], "only imports grew")
        (r / "a.py").write_text(code + "y = 1\n")
        found, _ = find_smells(r, [r / "a.py"], "HEAD")
        self.assertIn("the file is 26 lines long (hard limit 20; was 25)", [s.text() for s in found])

    def test_code_lines_leave_out_imports_however_wrapped(self) -> None:
        ts = ('import {\n  a,\n  b,\n} from "./x";\nimport c from "c";\nexport { d } from "./d";\n'
              'const e = require("e");\n\nexport const f = a + b;\n')
        self.assertEqual(code_lines("m.ts", ts), 2)
        calls = 'run(require("x"), () => {\n  go();\n});\nimport("./y").then((m) => {\n  m.go();\n});\n'
        self.assertEqual(code_lines("m.ts", calls), 6, "a call that requires or imports in passing is code")
        self.assertEqual(code_lines("m.go", 'package m\n\nimport (\n\t"fmt"\n\t"os"\n)\n\nfunc F() {}\n'), 4)
        self.assertEqual(code_lines("m.py", '"""Doc.\n\nfrom the base\n"""\nimport os\n'), 4, "prose isn't an import")
        self.assertEqual(code_lines("m.rs", "use a;\n"), 1, "a language broom doesn't measure: every line")
